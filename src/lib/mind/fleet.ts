function finish(run: AgentRun, state: RunState, at: string, error = ""): AgentRun {
  return { ...run, state, error, updatedAt: at, leaseUntil: null, workerId: null };
}

function advanceWithResult(run: AgentRun, detail: string, recordIds: string[] = []): AgentRun {
  const full = [run.result, detail].filter(Boolean).join("\n");
  const marker = "\n[Result excerpt truncated]";
  const result = full.length <= 4000 ? full : full.slice(0, 4000 - marker.length) + marker;
  const step = run.plan[run.step];
  const receipt: RunStepResult[] = step ? [{ stepId: step.id, tool: step.tool, output: detail.slice(0, 4000), at: run.updatedAt, recordIds }] : [];
  return { ...run, result, step: run.step + 1, stepResults: [...(run.stepResults ?? []), ...receipt] };
}

function quoteUrl(goal: string) {
  const candidate = goal.split(/\s+/).find((part) => HTTP.test(part));
  if (!candidate) return "";
  try { const url = new URL(candidate); return ["http:", "https:"].includes(url.protocol) && !url.username && !url.password ? url.href : ""; }
  catch { return ""; }
}

export function tickFleet(ws: Workspace, env: TickEnv): Workspace {
  const fleet = readFleet(ws);
  const at = env.now;
  if (ws.halted) return haltFleet(ws, at);
  const extra: AgentRun[] = [];
  let processed = 0;
  const runs = fleet.runs.map((run) => {
    if (processed >= 4 || TERMINAL.has(run.state) || run.state === "paused" || run.state === "waiting_approval" || run.state === "waiting_external") return run;
    if (run.leaseUntil && run.leaseUntil > at && run.workerId && run.workerId !== env.workerId) return run;
    processed += 1;
    const agent = fleet.agents.find((item) => item.id === run.agentId);
    if (!agent || agent.archived) {
      const reason = agent ? "This bot was archived before the run could finish." : "The agent definition is gone.";
      event(fleet, run.id, at, "failed", reason);
      return finish(run, "failed", at, reason);
    }
    const claimed = { ...run, state: "running" as const, workerId: env.workerId, leaseUntil: new Date(Date.parse(at) + 30_000).toISOString(), updatedAt: at };
    const plannedStep = claimed.plan[claimed.step];
    const tool = plannedStep?.tool;
    if (!claimed.plan.length) {
      const reason = "This run has no saved execution plan. Review and queue a new run; no operation was dispatched.";
      event(fleet, claimed.id, at, "failed", reason);
      return finish(claimed, "failed", at, reason);
    }
    if (tool && claimed.step >= claimed.maxSteps) {
      const reason = `Step budget exhausted after ${claimed.step} of ${claimed.plan.length} planned steps. Remaining work was not completed.`;
      event(fleet, claimed.id, at, "failed", reason);
      return finish(claimed, "failed", at, reason);
    }
    if (!tool) {
      const lines = fleet.runEvents.filter((item) => item.runId === claimed.id && item.kind === "tool_result").map((item) => item.detail);
      event(fleet, claimed.id, at, "completed", lines.length ? "Finished from tool results." : "Finished with no tool results.");
      return finish({ ...claimed, result: claimed.result || lines.join("\n").slice(0, 4000) || "Finished with no tool results." }, "completed", at);
    }
    if (!agent.tools.includes(tool)) {
      const reason = `The saved plan requires ${tool}, but this bot no longer permits it. Review the plan before resuming.`;
      event(fleet, claimed.id, at, "capability_removed", reason);
      return finish(claimed, "paused", at, reason);
    }
    if (agent.projectId && !ws.projects.some((project) => project.id === agent.projectId)) {
      const reason = "The bot's project no longer exists. Reassign it before running; no saved project context was read.";
      event(fleet, claimed.id, at, "invalid_project", reason);
      return finish(claimed, "paused", at, reason);
    }
    const receipts = claimed.stepResults ?? [];
    // A legacy run can preserve already-completed independent steps, but cannot fabricate a dependency input.
    const unresolved = plannedStep.dependsOn.some((id) => {
      const index = claimed.plan.findIndex((step) => step.id === id);
      return index < 0 || index >= claimed.step || (claimed.planVersion !== undefined && !receipts.some((receipt) => receipt.stepId === id));
    });
    const source = plannedStep.inputFrom && receipts.find((receipt) => receipt.stepId === plannedStep.inputFrom!.stepId);
    if (unresolved || plannedStep.inputFrom && (!source || !plannedStep.dependsOn.includes(plannedStep.inputFrom.stepId))) {
      const reason = "A required step result is missing or invalid. The dependent operation was not dispatched.";
      event(fleet, claimed.id, at, "dependency_failed", reason);
      return finish(claimed, "failed", at, reason);
    }
    const stepQuery = source ? (plannedStep.inputFrom?.field === "recordIds" ? (source.recordIds ?? []).join(" ") : source.output) : claimed.goal;
    if (plannedStep.inputFrom && !stepQuery.trim()) {
      return finish(claimed, "failed", at, "The declared dependency returned no usable input. Nothing was dispatched.");
    }
    if (tool === "delegate") {
      if (claimed.depth >= 1) {
        event(fleet, claimed.id, at, "tool_result", "Child runs do not delegate again.");
        return advanceWithResult(claimed, "Child runs do not delegate again.");
      }
      const kids = [...fleet.runs, ...extra].filter((item) => item.parentId === claimed.id);
      const open = kids.filter((item) => !TERMINAL.has(item.state));
      if (kids.length === 0) {
        const goals = delegationGoals(claimed.goal);
        const plan = goals.map((part, index) => ({
          id: `child-${index + 1}`,
          title: part.slice(0, 160),
          tool: "delegate" as const,
          dependsOn: [] as string[],
          need: "none" as const,
        }));
        event(fleet, claimed.id, at, "plan_generated", JSON.stringify(plan));
        for (const part of goals) {
          const child: AgentRun = {
            ...claimed,
            id: nid("run"),
            parentId: claimed.id,
            depth: 1,
            goal: part,
            state: "queued",
            step: 0,
            workerId: null,
            leaseUntil: null,
            result: "",
            error: "",
            createdAt: at,
            updatedAt: at,
            approvedActions: [],
            approvals: [],
            stepResults: [],
            plan: buildTaskPlan(part, claimed.plan.map((step) => step.tool).filter((step) => step !== "delegate")),
          };
          extra.push(child);
          event(fleet, child.id, at, "task_created", "Delegated from the parent run.");
        }
        event(fleet, claimed.id, at, "delegated", `Delegated ${goals.length} child run${goals.length === 1 ? "" : "s"}.`);
        return claimed;
      }
      if (open.length) return claimed;
      const detail = kids.map((item) => item.result || item.error || item.state).join(" | ");
      if (kids.some((child) => child.state !== "completed")) {
        const state = kids.every((child) => child.state === "canceled") ? "canceled" : "failed";
        const outcome = kids.map((child) => child.id + ": " + child.state).join(", ");
        event(fleet, claimed.id, at, state, outcome);
        return finish({ ...claimed, result: detail }, state, at, outcome);
      }
      event(fleet, claimed.id, at, "tool_result", detail || "Child runs finished.");
      return advanceWithResult(claimed, detail);
    }
    if (LOCAL.has(tool)) {
      const local = tool as LocalTool;
      const scope = {
        ...ws,
        projects: agent.projectId ? ws.projects.filter((project) => project.id === agent.projectId) : ws.projects,
        chats: ws.chats.filter((chat) => !chat.archived && !chat.temporary && (!agent.projectId || chat.projectId === agent.projectId)),
        memories: agent.memory === "on" ? ws.memories.filter((note) => !note.archived && (note.scope === "global" || (note.scope === "project" && !!agent.projectId && note.projectId === agent.projectId))) : [],
      };
      const executed = runLocalPlan(scope, [{ id: local, tool: local, query: stepQuery }], { autonomy: "automatic", halted: false, tokens: {} });
      const detail = executed.lines.join(" ");
      event(fleet, claimed.id, at, executed.ok ? "tool_result" : "failed", detail);
      if (!executed.ok) return finish(claimed, "failed", at, detail);
      return advanceWithResult(claimed, detail, executed.results?.flatMap((result) => result.records.map((record) => record.id)) ?? []);
    }
    if (tool === "browser" && !quoteUrl(stepQuery)) {
      const reason = "Choose an explicit http(s) destination for this read-page objective and queue a new run. No browser approval was consumed and no page was opened.";
      event(fleet, claimed.id, at, "destination_required", reason);
      return finish(claimed, "waiting_external", at, reason);
    }
    if (tool === "browser" || tool === "gmail_send") {
      const decision = decide({
        autonomy: agent.approval,
        kind: "publish",
        halted: false,
        approvalToken: (claimed.approvals ?? []).some((approval) => approval.stepId === plannedStep.id && approval.action === tool && !approval.consumedAt && approval.expiresAt >= at && approval.fingerprint === runOperationFingerprint(claimed, agent)) ? `approve:${claimed.id}:${tool}` : null,
        expectedToken: `approve:${claimed.id}:${tool}`,
      });
      if (decision.decision !== "allow") {
        event(fleet, claimed.id, at, "approval_requested", `${tool} needs approval. Nothing was sent or opened.`);
        return finish({ ...claimed, state: "waiting_approval" }, "waiting_approval", at, decision.reason);
      }
    }
    if (tool === "web_search") {
      const result = env.search?.(stepQuery) ?? { ok: false, citations: [], error: "No search provider is configured. Nothing was searched and no citations were created." };
      if (!result.ok || result.citations.length === 0) {
        event(fleet, claimed.id, at, "waiting_external", result.error);
        return finish(claimed, "waiting_external", at, result.error);
      }
      const detail = result.citations.map((item) => `${item.title} ${item.url}`).join(" | ");
      event(fleet, claimed.id, at, "tool_result", detail);
      return advanceWithResult(claimed, detail);
    }
    if (tool === "browser") {
      if (!env.browser) {
        const error = "No browser driver is attached. No page was opened.";
        event(fleet, claimed.id, at, "waiting_external", error);
        return finish(claimed, "waiting_external", at, error);
      }
      const url = quoteUrl(stepQuery);
      if (!url) {
        const error = "The goal has no http(s) URL. No page was opened.";
        event(fleet, claimed.id, at, "failed", error);
        return finish(claimed, "failed", at, error);
      }
      // Consume this approval at dispatch, not when a missing adapter is reported.
      claimed.approvals = (claimed.approvals ?? []).map((approval) => approval.stepId === plannedStep.id ? { ...approval, consumedAt: at } : approval);
      let opened: ReturnType<NonNullable<TickEnv["browser"]>>;
      try { opened = env.browser(url, { url, goal: stepQuery, capability: "read_page" }); }
      catch {
        const reason = "The browser driver lost contact after dispatch. The page-open outcome is unknown; verify it before starting a new operation.";
        event(fleet, claimed.id, at, "outcome_unknown", reason);
        return finish({ ...claimed, cancellation: "outcome_unknown" }, "failed", at, reason);
      }
      fleet.browserSessions.unshift({
        id: nid("tab"),
        runId: claimed.id,
        url,
        title: opened.ok ? opened.title : "",
        status: opened.ok ? "open" : "failed",
        lastAction: opened.ok ? "Read one approved page. No page interaction was performed." : opened.error,
        excerpt: opened.ok ? opened.excerpt.slice(0, 500) : "",
        updatedAt: at,
      });
      if (!opened.ok) {
        event(fleet, claimed.id, at, "failed", opened.error);
        return finish(claimed, "failed", at, opened.error);
      }
      const detail = `Read-page evidence: ${opened.title} ${url}\n${opened.excerpt.slice(0, 3000)}\nCapability used: read_page. No form, click, account change or navigation sequence was performed.`;
      event(fleet, claimed.id, at, "tool_result", detail);
      return advanceWithResult(claimed, detail);
    }
    if (tool === "gmail_read" || tool === "gmail_send") {
      const error = "This local worker has no Gmail execution adapter. A saved account authorization does not enable mailbox access here. Nothing was read or sent.";
      event(fleet, claimed.id, at, "waiting_external", error);
      return finish(claimed, "waiting_external", at, error);
    }
    const error = "This worker does not call a model. Nothing was sent.";
    event(fleet, claimed.id, at, "waiting_external", error);
    return finish(claimed, "waiting_external", at, error);
  });
  const scheduleNeedsReconcile = fleet.schedules.some((job) => (job.occurrences ?? []).some((occurrence) => {
    const run = runs.find((item) => item.id === occurrence.runId);
    return run && (occurrence.state !== run.state || occurrence.updatedAt !== run.updatedAt || job.resultDelivery === "conversation" && run.state === "completed" && !occurrence.deliveredAt && !occurrence.deliveryError);
  }) || (() => {
    const run = runs.find((item) => item.id === job.lastQueuedRunId);
    return !!run && TERMINAL.has(run.state) && (run.state === "completed" ? job.lastRunAt !== run.updatedAt || job.lastStatus !== "ran" : job.lastStatus !== "failed" || job.lastError !== (run.error || run.state));
  })());
  if (processed === 0 && extra.length === 0 && !scheduleNeedsReconcile) return ws;
  let chats = ws.chats;
  const schedules = fleet.schedules.map((job) => {
    const occurrences = (job.occurrences ?? []).map((occurrence) => {
      const outcome = runs.find((item) => item.id === occurrence.runId);
      if (!outcome) return occurrence;
      const next = { ...occurrence, state: outcome.state, updatedAt: outcome.updatedAt, detail: outcome.error || outcome.result.slice(0, 500) };
      if (job.resultDelivery !== "conversation" || outcome.state !== "completed" || occurrence.deliveredAt || occurrence.deliveryError) return next;
      const chat = chats.find((item) => item.id === job.chatId && !item.archived && !item.temporary);
      if (!chat) return { ...next, deliveryError: "The original conversation is missing, archived or temporary. The result remains in Runs; no other conversation was selected." };
      const messageId = "scheduled-result:" + occurrence.id;
      if (!chat.messages.some((message) => message.id === messageId)) {
        chats = chats.map((item) => item.id !== chat.id ? item : { ...item, messages: [...item.messages, {
          id: messageId, role: "assistant" as const, at,
          content: `Scheduled bot task: ${job.name}\n${outcome.result || "The workflow completed without text output."}\n\nRun: ${outcome.id}. This is a saved tool-workflow result; no conversation model was called.`,
          provider: "Local workflow", model: "no model call",
        }] });
      }
      return { ...next, deliveredAt: at };
    });
    job = { ...job, occurrences };
    if (!job.lastQueuedRunId) return job;
    const run = runs.find((item) => item.id === job.lastQueuedRunId);
    if (!run || !TERMINAL.has(run.state)) return job;
    return run.state === "completed"
      ? { ...job, lastRunAt: run.updatedAt, lastStatus: "ran" as const }
      : { ...job, lastStatus: "failed" as const, lastError: run.error || run.state };
  });
  return withFleet({ ...ws, chats }, { ...fleet, schedules, runs: [...extra, ...runs] });
}

export function setSchedulePolicy(ws: Workspace, id: string, policy: {
  missedPolicy?: NonNullable<ScheduleJob["missedPolicy"]>;
  overlapPolicy?: NonNullable<ScheduleJob["overlapPolicy"]>;
  resultDelivery?: NonNullable<ScheduleJob["resultDelivery"]>;
}): Workspace {
  if (ws.halted) return ws;
  return { ...ws, schedules: ws.schedules.map((job) => job.id === id ? { ...job,
    ...(policy.missedPolicy && ["once", "skip", "review"].includes(policy.missedPolicy) ? { missedPolicy: policy.missedPolicy } : {}),
    ...(policy.overlapPolicy && ["wait", "skip", "parallel"].includes(policy.overlapPolicy) ? { overlapPolicy: policy.overlapPolicy } : {}),
    ...(policy.resultDelivery && ["runs", "conversation"].includes(policy.resultDelivery) ? { resultDelivery: policy.resultDelivery, occurrences: job.occurrences?.map((occurrence) => ({ ...occurrence, deliveryError: undefined })) } : {}),
  } : job) };
}

export function runDueSchedules(ws: Workspace, now: string): Workspace {
  if (ws.halted) return ws;
  let next = ws;
  let changed = false;
  const jobs = ws.schedules.map((job) => {
    if (!job.enabled || job.nextRunAt > now) return job;
    changed = true;
    if (job.chatId && !next.chats.some((chat) => chat.id === job.chatId && !chat.temporary && !chat.archived)) {
      return { ...job, enabled: false, lastAttemptAt: now, lastError: "The scheduled conversation is unavailable." };
    }
    const agent = next.agents.find((item) => item.id === job.agentId && !item.archived);
    if (!agent) return { ...job, enabled: false, lastAttemptAt: now, lastError: "That agent is not on this device. Nothing was queued." };
    let recovery: ReturnType<typeof scheduleRecovery>;
    try { recovery = scheduleRecovery(job, now); }
    catch (error) { return { ...job, enabled: false, lastAttemptAt: now, lastError: error instanceof Error ? error.message : "Invalid schedule." }; }
    const occurrenceId = "scheduled:" + job.id + ":" + job.nextRunAt;
    const record = (state: ScheduleOccurrence["state"], detail: string, runId?: string) => [
      { id: occurrenceId, dueAt: job.nextRunAt, runId, state, updatedAt: now, detail, missedCount: Math.max(0, recovery.dueCount - 1) },
      ...(job.occurrences ?? []).filter((item) => item.id !== occurrenceId),
    ].slice(0, 100);
    const policy = job.missedPolicy ?? "once";
    const explicitCatchUp = job.approvedCatchUpFor === job.nextRunAt;
    if (recovery.overdue && policy === "review" && !explicitCatchUp) {
      return { ...job, enabled: false, lastAttemptAt: now, lastError: "Missed occurrences require review. Choose a recovery policy, then enable the next occurrence or explicitly queue one catch-up." };
    }
    if (recovery.overdue && policy === "skip" && !explicitCatchUp) {
      const detail = `Skipped ${recovery.dueCount} due occurrences under the saved recovery policy. No work was dispatched.`;
      return { ...job, nextRunAt: recovery.nextRunAt, lastAttemptAt: now, lastError: "", occurrences: record("skipped", detail) };
    }
    const active = next.runs.filter((run) => run.id.startsWith("scheduled:" + job.id + ":") && !TERMINAL.has(run.state) && run.id !== occurrenceId);
    const overlap = job.overlapPolicy ?? "wait";
    if (active.length && (overlap === "wait" || overlap === "parallel" && active.length >= 4)) {
      return { ...job, lastAttemptAt: now, lastError: `Waiting for ${active.length} unfinished occurrence${active.length === 1 ? "" : "s"}. No additional run was queued.` };
    }
    if (active.length && overlap === "skip") {
      return { ...job, nextRunAt: recovery.nextRunAt, lastAttemptAt: now, lastError: "", occurrences: record("skipped", "Skipped because an earlier occurrence is unfinished.") };
    }
    const existing = next.runs.find((run) => run.id === occurrenceId);
    const queued = existing ? { ok: true as const, ws: next, run: existing } : enqueueRun(next, agent.id, job.instruction || job.name, now, null, 0, occurrenceId);
    if (!queued.ok) return { ...job, enabled: false, lastAttemptAt: now, lastError: queued.error };
    next = queued.ws;
    const detail = recovery.overdue ? `One catch-up queued; ${recovery.dueCount - 1} additional missed occurrences were not replayed.` : "Scheduled bot workflow queued. Results appear in Runs.";
    return { ...job, approvedCatchUpFor: undefined, lastAttemptAt: now, lastQueuedRunId: queued.run.id, lastError: "", nextRunAt: recovery.nextRunAt, occurrences: record(queued.run.state, detail, queued.run.id) };
  });
  return changed ? { ...next, schedules: jobs } : ws;
}
