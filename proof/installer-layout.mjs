import { chromium } from "playwright";

const root = "/home/ubuntu/adrians-mind-command-os/proof/phone";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const report = {};
await page.goto("http://127.0.0.1:8080/", { waitUntil: "domcontentloaded" });
await page.getByRole("button", { name: "Open menu" }).click();
await page.getByRole("button", { name: "Build", exact: true }).first().click();
await page.getByRole("button", { name: "Actions", exact: true }).click();
await page.getByTestId("windows-installer-ready").waitFor();
report.text = (await page.getByTestId("windows-installer-ready").textContent())?.trim();
report.href = await page.getByTestId("download-installer").getAttribute("href");
report.mouseDisabled = await page.getByTestId("desktop-run-mouse").isDisabled();
report.keyboardDisabled = await page.getByTestId("desktop-run-keyboard").isDisabled();
report.screenDisabled = await page.getByTestId("desktop-run-screen").isDisabled();
report.fileDisabled = await page.getByTestId("desktop-run-pc_file").isDisabled();
report.hostedDisabled = await page.getByTestId("run-file_read").isDisabled();
const response = await page.request.get("http://127.0.0.1:8080/downloads/AdriansMind-Setup.exe");
report.status = response.status();
report.bytes = (await response.body()).byteLength;
await page.getByTestId("owner-flow").screenshot({ path: `${root}/build-installer.png` });
await page.getByRole("button", { name: "Open menu" }).click();
await page.locator("summary", { hasText: "More" }).click();
await page.getByRole("button", { name: "Skills", exact: true }).click();
await page.getByRole("button", { name: "Installed", exact: true }).click();
await page.screenshot({ path: `${root}/skills-installed.png` });
await page.getByRole("button", { name: "Not installed", exact: true }).click();
await page.screenshot({ path: `${root}/skills-missing.png` });
console.log(JSON.stringify(report, null, 2));
await browser.close();
if (!report.mouseDisabled || report.status !== 200) process.exit(1);
