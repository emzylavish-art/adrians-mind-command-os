import { chromium } from "playwright";

const root = "/home/ubuntu/adrians-mind-command-os/proof/phone";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
const report = {};
await page.goto("http://127.0.0.1:8080/", { waitUntil: "domcontentloaded" });
await page.getByRole("button", { name: "Open menu" }).click();
await page.getByRole("button", { name: "Build", exact: true }).first().click();
await page.getByRole("navigation", { name: "Build sections" }).getByRole("button", { name: "Actions", exact: true }).click();
await page.getByTestId("owner-flow-speak").click();
await page.getByTestId("speak-stage").waitFor();
report.face = await page.getByTestId("speak-face").getAttribute("src");
report.stopOnSpeak = await page.getByRole("button", { name: "Emergency stop" }).count();
await page.getByRole("button", { name: "Place call" }).click();
await page.getByTestId("speak-status").filter({ hasText: "Spoken:" }).waitFor({ timeout: 80000 });
report.status = (await page.getByTestId("speak-status").textContent())?.trim();
report.reply = (await page.getByTestId("speak-reply").textContent())?.trim();
await page.screenshot({ path: `${root}/speak-reply-retest.png` });
await page.getByRole("button", { name: "End call" }).click();
await page.getByTestId("speak-stage").waitFor({ state: "hidden" });
await page.getByTestId("owner-flow-stop").click();
await page.getByTestId("owner-flow-halt").filter({ hasText: "Emergency stop is on" }).waitFor();
report.runDisabled = await page.getByTestId("run-file_read").isDisabled();
report.stopText = (await page.getByTestId("owner-flow-halt").textContent())?.trim();
await page.getByTestId("owner-flow-speak").click();
report.stopOnSpeakAfterHalt = await page.getByRole("button", { name: "Emergency stop" }).count();
report.speakCannotClear = await page.getByRole("button", { name: "Clear stop" }).count();
await page.screenshot({ path: `${root}/speak-stop-retest.png` });
await page.getByRole("button", { name: "End call" }).click();
await page.getByTestId("owner-flow-stop").click();
report.cleared = (await page.getByTestId("owner-flow-halt").textContent())?.trim();
console.log(JSON.stringify(report, null, 2));
await browser.close();
if (!report.status?.startsWith("Spoken:") || report.stopOnSpeak !== 0 || report.runDisabled !== true) process.exit(1);
